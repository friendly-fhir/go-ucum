// Command genucum compiles a ucum-essence XML document into Go source that
// declares the definitions as package ucum's DefaultRegistry.
//
// Compiling the definitions in, rather than embedding and parsing the XML at
// start-up, means the default registry costs no decoding at run time and has
// already been validated when the code was generated:
//
//	go run ./internal/cmd/genucum -in internal/data/ucum-essence.xml -out default_registry.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"math/big"
	"os"
	"strconv"

	"github.com/friendly-fhir/go-ucum/internal/model"
	"github.com/friendly-fhir/go-ucum/internal/xmldef"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "genucum:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	flags := flag.NewFlagSet("genucum", flag.ContinueOnError)
	in := flags.String("in", "", "path of the ucum-essence document to compile")
	out := flags.String("out", "", "path to write the Go source to")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if *in == "" || *out == "" {
		return fmt.Errorf("both -in and -out are required")
	}

	file, err := os.Open(*in)
	if err != nil {
		return err
	}
	defer file.Close()
	defs, err := xmldef.Decode(file)
	if err != nil {
		return fmt.Errorf("%s: %w", *in, err)
	}
	if _, err := model.NewResolver(defs, 1); err != nil {
		return fmt.Errorf("%s: %w", *in, err)
	}

	source, err := format.Source(generate(defs))
	if err != nil {
		return err
	}
	return os.WriteFile(*out, source, 0o644)
}

// generate returns Go source declaring defs as the DefaultRegistry.
func generate(defs *model.Definitions) []byte {
	rats := newConstants(defs)
	var body bytes.Buffer
	fmt.Fprintf(&body, "return &Registry{defs: &model.Definitions{\n")
	fmt.Fprintf(&body, "Version: %s,\n", strconv.Quote(defs.Version))
	fmt.Fprintf(&body, "RevisionDate: %s,\n", strconv.Quote(defs.RevisionDate))

	body.WriteString("Prefixes: []model.Prefix{\n")
	for _, p := range defs.Prefixes {
		fmt.Fprintf(&body, "{Code: %s, CICode: %s, Value: %s},\n", strconv.Quote(p.Code), strconv.Quote(p.CICode), rats.name(p.Value))
	}
	body.WriteString("},\n")

	body.WriteString("BaseUnits: []model.BaseUnit{\n")
	for _, u := range defs.BaseUnits {
		fmt.Fprintf(&body, "{Code: %s, CICode: %s},\n", strconv.Quote(u.Code), strconv.Quote(u.CICode))
	}
	body.WriteString("},\n")

	body.WriteString("Units: []model.Unit{\n")
	for _, u := range defs.Units {
		fmt.Fprintf(&body, "{Code: %s, CICode: %s", strconv.Quote(u.Code), strconv.Quote(u.CICode))
		if u.Metric {
			body.WriteString(", Metric: true")
		}
		if u.Special {
			body.WriteString(", Special: true")
		}
		if u.Arbitrary {
			body.WriteString(", Arbitrary: true")
		}
		if u.Function != nil {
			fmt.Fprintf(&body, ", Function: &model.Function{Name: %s, Value: %s, Term: %s}",
				strconv.Quote(u.Function.Name), rats.name(u.Function.Value), strconv.Quote(u.Function.Term))
		} else {
			fmt.Fprintf(&body, ", Value: %s, Term: %s", rats.name(u.Value), strconv.Quote(u.Term))
		}
		body.WriteString("},\n")
	}
	body.WriteString("},\n")
	body.WriteString("}}\n")

	var b bytes.Buffer
	b.WriteString("// Code generated by genucum. DO NOT EDIT.\n\n")
	b.WriteString("package ucum\n\n")
	b.WriteString("import \"github.com/friendly-fhir/go-ucum/internal/model\"\n\n")
	fmt.Fprintf(&b, "// DefaultRegistry holds the definitions of UCUM %s, published %s.\n", defs.Version, defs.RevisionDate)
	b.WriteString("var DefaultRegistry = defaultRegistry()\n\n")
	b.WriteString("func defaultRegistry() *Registry {\n")
	for i, value := range rats.values {
		fmt.Fprintf(&b, "r%d := model.MustRat(%s)\n", i, strconv.Quote(value))
	}
	b.WriteString("\n")
	b.Write(body.Bytes())
	b.WriteString("}\n")
	return b.Bytes()
}

// constants assigns one local variable to each rational that occurs more
// than once in the definitions, so that equal values share a single parsed
// instance. Rationals that occur once are written inline.
type constants struct {
	uses   map[string]int
	index  map[string]int
	values []string
}

func newConstants(defs *model.Definitions) *constants {
	c := &constants{uses: map[string]int{}, index: map[string]int{}}
	for _, p := range defs.Prefixes {
		c.uses[p.Value.RatString()]++
	}
	for _, u := range defs.Units {
		if u.Function != nil {
			c.uses[u.Function.Value.RatString()]++
		} else {
			c.uses[u.Value.RatString()]++
		}
	}
	return c
}

// name returns the expression for r: the variable shared by every occurrence
// of a repeated value, or a direct parse of a value that occurs once.
func (c *constants) name(r *big.Rat) string {
	value := r.RatString()
	if c.uses[value] < 2 {
		return fmt.Sprintf("model.MustRat(%s)", strconv.Quote(value))
	}
	i, ok := c.index[value]
	if !ok {
		i = len(c.values)
		c.index[value] = i
		c.values = append(c.values, value)
	}
	return fmt.Sprintf("r%d", i)
}
